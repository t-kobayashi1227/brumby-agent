export const NEW_BUILD_MAX_AGE = 1;

export function ageClassOf(age: number): "新築" | "築2〜20年" | "築21年以上" {
  if (age <= NEW_BUILD_MAX_AGE) return "新築";
  if (age <= 20) return "築2〜20年";
  return "築21年以上";
}
